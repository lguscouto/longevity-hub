def get_derived_metrics_by_category() -> dict[str, list[DerivedMetricSpec]]:
    """Agrupa o catálogo nas 7 categorias oficiais da especificação (§12)."""
    categories: dict[str, list[DerivedMetricSpec]] = {
        "biological_age": [],
        "metabolic_insulin": [],
        "inflammation_immune_nutrition": [],
        "hepatic": [],
        "cardiovascular_renal": [],
        "body_composition": [],
        "direct_biomarkers": [],
    }
    for spec in DERIVED_METRICS_CATALOG.values():
        if spec.category in categories:
            categories[spec.category].append(spec)
    return categories


def get_derived_metric_definition(metric_id: str) -> DerivedMetricSpec | None:
    """Retorna a especificação de uma métrica derivada pelo seu identificador único."""
    return DERIVED_METRICS_CATALOG.get(metric_id)

